package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

// buildSkeleton turns UTS #39 confusables.txt into the Go table the pack uses.
//
// It keeps only mappings that say "this looks like English": a single source
// character at or above U+0080 whose prototype is ASCII letters and digits. The
// ASCII sources are dropped (UTS #39 maps 'm' to "rn" and 'I' to 'l', which is
// right for spoof detection and wrong for reading chat), and so are sources NFKC
// already rewrites, since the pack runs NFKC first.
func buildSkeleton(src []byte, version string) ([]byte, int, error) {
	type ent struct {
		r  rune
		to string
	}
	var ents []ent
	sc := bufio.NewScanner(bytes.NewReader(src))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(strings.TrimPrefix(line, "\xef\xbb\xbf"))
		if line == "" {
			continue
		}
		f := strings.Split(line, ";")
		if len(f) < 2 {
			return nil, 0, fmt.Errorf("confusables.txt: unparseable line %q", line)
		}
		srcs := strings.Fields(f[0])
		if len(srcs) != 1 {
			continue
		}
		cp, err := strconv.ParseUint(srcs[0], 16, 32)
		if err != nil {
			return nil, 0, fmt.Errorf("confusables.txt: %q: %w", srcs[0], err)
		}
		r := rune(cp)
		if r < 0x80 || unicode.Is(unicode.Cf, r) || norm.NFKC.String(string(r)) != string(r) {
			continue
		}
		var to strings.Builder
		ok := true
		for _, t := range strings.Fields(f[1]) {
			tc, err := strconv.ParseUint(t, 16, 32)
			if err != nil {
				return nil, 0, fmt.Errorf("confusables.txt: %q: %w", t, err)
			}
			c := rune(tc)
			switch {
			case 'a' <= c && c <= 'z', '0' <= c && c <= '9':
				to.WriteRune(c)
			case 'A' <= c && c <= 'Z':
				to.WriteRune(c + 'a' - 'A')
			default:
				ok = false
			}
		}
		if ok && to.Len() > 0 {
			ents = append(ents, ent{r, to.String()})
		}
	}
	if err := sc.Err(); err != nil {
		return nil, 0, err
	}
	sort.Slice(ents, func(i, j int) bool { return ents[i].r < ents[j].r })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by scripts/gen-pack -skeleton; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package pack\n\n")
	fmt.Fprintf(&b, "// skeletonTable is derived from the Unicode Security Mechanisms confusables.txt,\n")
	fmt.Fprintf(&b, "// version %s (the Unicode version Go's unicode package tracks), under the\n", version)
	fmt.Fprintf(&b, "// Unicode License v3. See LICENSES/LICENSE-Unicode-3.0.txt.\n//\n")
	fmt.Fprintf(&b, "// Only single non-ASCII characters whose prototype is ASCII letters and digits\n")
	fmt.Fprintf(&b, "// are kept, lowercased. Sorted by rune.\n")
	fmt.Fprintf(&b, "var skeletonTable = [...]struct {\n\tr  rune\n\tto string\n}{\n")
	for _, e := range ents {
		fmt.Fprintf(&b, "\t{0x%04X, %q},\n", e.r, e.to)
	}
	fmt.Fprintf(&b, "}\n")
	out, err := format.Source(b.Bytes())
	return out, len(ents), err
}
