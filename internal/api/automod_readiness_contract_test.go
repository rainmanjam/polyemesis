// WHEN A CHECKER IS CONFIGURED IS DECIDED IN TWO PLACES, AND THIS IS THE ONE
// TABLE THEY ANSWER TO.
//
// checkerConfigured (automod.go) judges stored settings; the console's
// checkerReady (ui/src/lib/automodConfig.ts) judges the same settings while
// they are still a draft, because a draft cannot be sent to the server to ask.
// The comment on each said "the two must agree", and nothing made them: where
// they disagreed the console read "nothing automatic" while the banner said a
// ban was armed. This test runs the settings of each case below through the
// server's rule and writes the verdict beside the settings; the console's test
// (ui/src/lib/contract/automod-readiness.test.ts) runs the SAME settings
// through checkerReady and expects the same verdict and the same reason.
//
// Regenerate with: go test ./internal/api/ -run TestAutomodReadinessContract -update-wire-contract
const automodReadinessFile = "../../ui/src/lib/contract/automod-readiness.json"

type automodReadinessCase struct {
	Name     string          `json:"name"`
	Settings json.RawMessage `json:"settings"`
	Checker  string          `json:"checker"`
	Ready    bool            `json:"ready"`
	// Reason is the code of why not (the console's "automod.<reason>" message);
	// empty when ready.
	Reason string `json:"reason,omitempty"`
}

// automodReasonCodes names the server's refusal sentences. A sentence that is
// not here fails the test: a new refusal needs a code, and so a console message.
var automodReasonCodes = map[string]string{
	"no enabled rule is written":        "noRules",
	"the model checker is switched off": "modelOff",
	"the model checker has no endpoint": "modelNoEndpoint",
}

func TestAutomodReadinessContract(t *testing.T) {
	const ruleOn = `{"id":1,"name":"spam","enabled":true,"pattern":"buy followers","action":"flag"}`
	cases := []struct{ name, checker, settings string }{
		{"no rules", "rules", `{"rules":[]}`},
		{"a disabled rule is no rule", "rules", `{"rules":[{"id":1,"name":"x","enabled":false,"pattern":"p","action":"flag"}]}`},
		{"a blank pattern is no rule", "rules", `{"rules":[{"id":1,"name":"x","enabled":true,"pattern":"   ","action":"flag"}]}`},
		{"one usable rule", "rules", `{"rules":[` + ruleOn + `]}`},
		{"a disabled rule beside a usable one", "rules", `{"rules":[{"id":2,"name":"y","enabled":false,"pattern":"p","action":"flag"},` + ruleOn + `]}`},
		{"model off", "model", `{"model":{"enabled":false,"endpoint":"https://m.example/v1"}}`},
		{"model on with no endpoint", "model", `{"model":{"enabled":true,"endpoint":""}}`},
		{"model on with a blank endpoint", "model", `{"model":{"enabled":true,"endpoint":"  "}}`},
		{"model on with an endpoint", "model", `{"model":{"enabled":true,"endpoint":"https://m.example/v1"}}`},
		{"the fallback alone is enough", "model", `{"model":{"enabled":false,"endpoint":""},"secondary":{"enabled":true,"endpoint":"https://s.example/v1"}}`},
		{"both on, neither has an endpoint", "model", `{"model":{"enabled":true,"endpoint":""},"secondary":{"enabled":true,"endpoint":""}}`},
		{"primary has none, the fallback has one", "model", `{"model":{"enabled":true,"endpoint":""},"secondary":{"enabled":true,"endpoint":"https://s.example/v1"}}`},
		{"history is always built", "history", `{}`},
	}

	var out []automodReadinessCase
	for _, c := range cases {
		var a db.AutomodSettings
		if err := json.Unmarshal([]byte(c.settings), &a); err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
		ok, why := checkerConfigured(a, automod.Checker(c.checker))
		row := automodReadinessCase{Name: c.name, Settings: json.RawMessage(c.settings), Checker: c.checker, Ready: ok}
		if !ok {
			code, known := automodReasonCodes[why]
			if !known {
				t.Fatalf("%s: checkerConfigured refused with %q, which has no reason code", c.name, why)
			}
			row.Reason = code
		}
		out = append(out, row)
	}
	want := marshalWire(t, map[string]any{
		"_comment": "Generated by internal/api's TestAutomodReadinessContract. Do not edit by hand: " +
			"regenerate with `go test ./internal/api/ -run TestAutomodReadinessContract -update-wire-contract`.",
		"cases": out,
	})

	if *updateWireContract {
		if err := os.MkdirAll(filepath.Dir(automodReadinessFile), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(automodReadinessFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(automodReadinessFile)
	if err != nil || string(got) != string(want) {
		t.Errorf("%s is out of date or missing (%v). Regenerate with: "+
			"go test ./internal/api/ -run TestAutomodReadinessContract -update-wire-contract", automodReadinessFile, err)
	}
}
