// Writes ui/strings.js: the inspector's own copy of the strings it shows, for
// every locale, so the labels appear without waiting on the plugin. Only the
// keys the inspector and its test result use are included.
import { readFileSync, readdirSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const LOCALES = join(HERE, "..", "src", "locales");
const KEEP = /^streamdeck\.(pi|auth|err)\./;

/** The full source of ui/strings.js, built from the catalogs. Deterministic: the test compares it to the committed file. */
export function inspectorCatalogSource() {
  const catalogs = {};
  for (const file of readdirSync(LOCALES).filter((f) => f.endsWith(".json")).sort()) {
    const locale = basename(file, ".json");
    const all = JSON.parse(readFileSync(join(LOCALES, file), "utf8"));
    catalogs[locale] = Object.fromEntries(Object.entries(all).filter(([k]) => KEEP.test(k)).sort(([a], [b]) => (a < b ? -1 : 1)));
  }
  return (
    "// GENERATED by scripts/inspectorCatalog.mjs from src/locales/*.json. Do not edit by hand.\n" +
    "window.POLYEMESIS_STRINGS = " +
    JSON.stringify(catalogs, null, 2) +
    ";\n"
  );
}
